// DefaultRealitySNIs returns SNI hostnames from DefaultRealityProfiles.
func DefaultRealitySNIs() []string {
	ps := DefaultRealityProfiles()
	out := make([]string, 0, len(ps))
	for _, p := range ps {
		out = append(out, p.SNI)
	}
	return out
}
